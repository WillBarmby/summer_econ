function manifest = experiment()
%% EXPERIMENT Define one self-contained model-based learning experiment.

folder = fileparts(mfilename('fullpath'));
manifest = struct( ...
    'case_definition',case_definition(folder), ...
    'study_options',study_options());
end

function definition = case_definition(folder)
definition = struct( ...
    'id',"tiny_linear", ...
    'label',"Tiny linear learning example", ...
    'model_file',fullfile(folder,'tiny_linear.mod'), ...
    'model_options',struct('kind',"linear", ...
        'parameter_overrides',struct()), ...
    'learning_specification_factory',@learning_specification, ...
    'reporting_specification',reporting_specification());
end

function specification = learning_specification(~)
specification = struct( ...
    'learned_variables',{{'y'}}, ...
    'regressors',{{ ...
        struct('name',"constant",'kind',"constant"), ...
        struct('name',"y_lag",'kind',"lagged_variable", ...
            'variable',"y",'lag',1)}}, ...
    'gain',struct('type',"constant",'value',0.25), ...
    'estimator',struct('method',"rls", ...
        'moment_timing',"update_before_coefficients", ...
        'rcond_tolerance',1e-12), ...
    'initialization',struct( ...
        'coefficients',struct('method',"re",'scale',1), ...
        'moments',struct('method',"stationary_re", ...
            'shock_covariance',1)), ...
    'update_timing',"decide_then_update", ...
    'projection',struct('variable',"y",'regressor',"y_lag", ...
        'criterion',"absolute_limit",'limit',0.99, ...
        'action',"retain_previous_coefficient"), ...
    'expectation_mapping',struct('method',"one_step",'options',struct()));
end

function specification = reporting_specification()
series = struct('id',"y",'label',"Y",'unit',"model_units", ...
    'transformation',struct('kind',"native",'variable',"y",'scale',1));
specification = struct('source',"irf",'series',series, ...
    'title',"Tiny linear impulse response", ...
    'x_label',"Periods",'y_label',"Model units");
end

function options = study_options()
options = learning_irf_options();
options.draw_count = 1;
options.training_periods = 8;
options.irf_periods = 5;
options.shock_name = "eps";
options.training_standard_deviation = 1;
end
