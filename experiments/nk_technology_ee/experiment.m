function manifest = experiment(options)
%% EXPERIMENT Define nonlinear NK technology-growth learning.

folder = fileparts(mfilename('fullpath'));
if nargin<1
    options = default_case_options();
end
manifest = struct( ...
    'case_definition',case_definition(folder,options), ...
    'study_options',study_options());
end

function definition = case_definition(folder,options)
definition = struct( ...
    'id',"nk_technology_ee", ...
    'label',"NK technology EE", ...
    'model_file',fullfile(folder,'nk_balanced_growth.mod'), ...
    'model_options',struct('kind',"nonlinear", ...
        'parameter_overrides',options.parameter_overrides, ...
        'deviation_scales',options.deviation_scales), ...
    'learning_specification_factory',@(model) learning_specification(model,options), ...
    'reporting_specification',reporting_specification());
end

function specification = learning_specification(model,options)
q = numel(model.shock_names);
[found,technology_index] = ismember('eps_x',model.shock_names);
if ~found
    error('AdaptiveLearning:UnknownShock', ...
        'NK technology case requires shock eps_x.');
end
covariance = options.belief_shock_covariance;
if ~isequal(size(covariance),[q q]) || covariance(technology_index,technology_index)<=0
    error('AdaptiveLearning:InvalidCaseOptions', ...
        'NK belief covariance must match the model shock declarations.');
end
specification = struct( ...
    'learned_variables',{{'rk','consumption','capital','inflation','output'}}, ...
    'regressors',{{struct('name',"constant",'kind',"constant"), ...
        struct('name',"capital_lag",'kind',"lagged_variable", ...
            'variable',"capital",'lag',1)}}, ...
    'gain',struct('type',"constant",'value',options.gain), ...
    'estimator',struct('method',"rls", ...
        'moment_timing',"update_before_coefficients", ...
        'rcond_tolerance',options.rcond_tolerance), ...
    'initialization',struct( ...
        'coefficients',struct('method',"re",'scale',1), ...
        'moments',struct('method',"stationary_re", ...
            'shock_covariance',covariance)), ...
    'update_timing',"decide_then_update", ...
    'projection',struct('variable',"capital",'regressor',"capital_lag", ...
        'criterion',"absolute_limit",'limit',0.99, ...
        'action',"retain_previous_coefficient"), ...
    'expectation_mapping',struct('method',"one_step",'options',struct()));
end

function specification = reporting_specification()
variables = {'output','consumption','investment','hours', ...
    'inflation','nominal_rate'};
labels = {'output','consumption','investment','hours', ...
    'inflation','nominal rate'};
series = repmat(struct('id',"",'label',"",'unit',"percent_deviation", ...
    'transformation',struct()),1,numel(variables));
for j = 1:numel(variables)
    series(j).id = string(variables{j});
    series(j).label = string(labels{j});
    if j<=3
        series(j).transformation = struct('kind',"add_cumulative", ...
            'variable',string(variables{j}), ...
            'cumulative_variables',{{'gamma_x'}},'scale',1);
    else
        series(j).transformation = struct('kind',"native", ...
            'variable',string(variables{j}),'scale',1);
    end
end
specification = struct('source',"irf",'series',series, ...
    'title',"NK technology impulse responses",'x_label',"Quarters", ...
    'y_label',"Percent deviation");
end

function options = study_options()
options = learning_irf_options();
options.draw_count = 1;
end

function options = default_case_options()
shock_scale = exp(-0.034);
options = struct('gain',0.002, ...
    'parameter_overrides',struct('rho_s',0,'sigma_s',0), ...
    'deviation_scales',struct('gamma_x',0.01), ...
    'belief_shock_covariance',diag([shock_scale^2 0]), ...
    'rcond_tolerance',1e-12);
end
