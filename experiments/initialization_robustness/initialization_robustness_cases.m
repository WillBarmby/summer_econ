function cases = initialization_robustness_cases(root,config)
%% INITIALIZATION_ROBUSTNESS_CASES Build the three paper specifications.

variance = config.training_shock_standard_deviation^2;
calibration = ep_calibration(config.gamma_bar);
ee_model = load_linear_dynare_model(fullfile(root,'models','ep_rbc_ee.mod'), ...
    'ParameterOverrides',calibration.parameter_overrides);
ih_model = load_linear_dynare_model(fullfile(root,'models','ep_rbc_ih.mod'), ...
    'ParameterOverrides',calibration.parameter_overrides);
nk_model = load_nonlinear_dynare_model( ...
    fullfile(root,'models','nk_balanced_growth.mod'), ...
    'DeviationScales',struct('gamma_x',0.01));

cases = struct('id',{'ep_ee','ep_ih','nk_ee'}, ...
    'label',{'E&P EE','E&P IH','NK EE'},'learning_model',{ ...
    build_ee_learning_model(ee_model,ep_ee_specification(config.gain),variance), ...
    build_ep_ih_learning_model(ih_model,ep_ih_specification(config.gain),variance), ...
    build_ee_learning_model(nk_model,nk_ee_specification(config.gain), ...
    diag([variance 0]))});
end
