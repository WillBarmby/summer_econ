function validate_ep_experiment_config(config)
%% VALIDATE_EP_EXPERIMENT_CONFIG Validate the complete public configuration.

required = {'gain','random_seed','draw_count','training_periods','ir_periods', ...
    'plot_periods','band_probabilities','technology_growth_impulse', ...
    'training_shock_standard_deviation','gamma_bar','explosion_magnitude'};
assert(isstruct(config) && isscalar(config) && ...
    isempty(setxor(fieldnames(config),required.')), ...
    'EPResearch:InvalidExperiment','Use the complete E&P configuration.');
positive_integers = [config.draw_count config.training_periods config.ir_periods];
assert(all(positive_integers>=1) && all(positive_integers==fix(positive_integers)), ...
    'EPResearch:InvalidExperiment','Draw and period counts must be positive integers.');
assert(config.gain>0 && config.gain<=1 && isfinite(config.gain), ...
    'EPResearch:InvalidExperiment','Gain must lie in (0,1].');
assert(isnumeric(config.random_seed) && isscalar(config.random_seed) && ...
    isfinite(config.random_seed),'EPResearch:InvalidExperiment', ...
    'Random seed must be a finite scalar.');
assert(all(config.plot_periods>=1) && all(config.plot_periods<=config.ir_periods), ...
    'EPResearch:InvalidExperiment','Plot periods must lie in the IRF horizon.');
assert(isequal(size(config.band_probabilities),[1 2]) && ...
    0<config.band_probabilities(1) && ...
    config.band_probabilities(1)<config.band_probabilities(2) && ...
    config.band_probabilities(2)<1,'EPResearch:InvalidExperiment', ...
    'Band probabilities must be two increasing values in (0,1).');
positive = [config.technology_growth_impulse, ...
    config.training_shock_standard_deviation,config.gamma_bar, ...
    config.explosion_magnitude];
assert(all(isfinite(positive)) && all(positive>0), ...
    'EPResearch:InvalidExperiment','Shock, growth, and explosion values must be positive.');
end
