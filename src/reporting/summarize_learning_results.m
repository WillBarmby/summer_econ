function summary = summarize_learning_results(results,specification_ids, ...
    quantity_names,periods)
%% SUMMARIZE_LEARNING_RESULTS Make paper-facing metrics for result collections.

assert(iscell(results) && numel(results)==numel(specification_ids), ...
    'EPResearch:SummaryDimensions','Results and specification IDs must align.');
S = numel(results);
Q = numel(quantity_names);
wedges = NaN(S,Q);
completed = NaN(S,1);
explosive = NaN(S,1);
invalid = NaN(S,1);
attempted = NaN(S,1);
for s = 1:S
    result = results{s};
    difference = result.summary.learning_median(:,periods)- ...
        result.summary.re(:,periods);
    wedges(s,:) = max(abs(difference),[],2,'omitnan').';
    completed(s) = result.status_counts.completed;
    explosive(s) = result.status_counts.explosive;
    invalid(s) = result.status_counts.invalid;
    attempted(s) = numel(result.statuses);
end
summary = struct('metric_description',[ ...
    'maximum over reported periods of the absolute pointwise median ' ...
    'learning-minus-own-RE response'], ...
    'response_unit',"percentage points of reported response", ...
    'reported_matlab_indices',periods,'reported_horizons',periods-1, ...
    'specification_ids',{cellstr(string(specification_ids))}, ...
    'quantity_names',{quantity_names}, ...
    'maximum_absolute_median_learning_minus_re_wedge',wedges, ...
    'attempted_draw_count',attempted,'completed_draw_count',completed, ...
    'explosive_draw_count',explosive,'invalid_draw_count',invalid, ...
    'completion_rate',completed./attempted, ...
    'failure_rate',(explosive+invalid)./attempted);
end
