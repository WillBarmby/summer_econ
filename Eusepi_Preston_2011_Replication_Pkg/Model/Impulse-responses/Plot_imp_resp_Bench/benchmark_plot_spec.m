function spec = benchmark_plot_spec(learning_completed,re_completed)
%% BENCHMARK_PLOT_SPEC Explicit paper-style benchmark figure specification.

if nargin ~= 2
    error('IRBenchmark:RequiredStatus', ...
        'Completed learning and RE draw counts are required.');
end
panel = @(kind,index,comparison,title_text,limits) struct( ...
    'kind',kind,'series_index',index,'comparison_series_index',comparison, ...
    'title',title_text,'y_limits',limits);
spec = struct('periods',1:40,'band_probabilities',[0.15 0.85], ...
    'visible','off','figure_size',[1100 760],'png_resolution',200, ...
    'line_width',1.6,'styles',struct('learning','k-', ...
    're','k--','band','k:'),'figures',[], ...
    'status',struct('learning_completed',learning_completed, ...
    're_completed',re_completed));
spec.figures = [ ...
    struct('file_stem','quantities','title','Quantities','layout',[2 2], ...
        'panels',[panel("standard",2,NaN,'Consumption',[]), ...
        panel("standard",4,NaN,'Output',[]),panel("standard",3,NaN,'Investment',[]), ...
        panel("standard",6,NaN,'Hours',[])]), ...
    struct('file_stem','expected_sums','title','Expected sums','layout',[2 1], ...
        'panels',[panel("standard",15,NaN,'Expected discounted capital income',[]), ...
        panel("standard",16,NaN,'Expected discounted labor income',[])]), ...
    struct('file_stem','forecast_errors','title','Forecast errors','layout',[1 1], ...
        'panels',panel("learning_minus_re",9,4, ...
        'Return forecast error and learning minus RE output',[])), ...
    struct('file_stem','long_horizon_forecast','title','Long-horizon forecast', ...
        'layout',[1 1],'panels',panel("standard",12,NaN, ...
        'Return to capital, 10 years ahead',[]))];
end
